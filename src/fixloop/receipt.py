"""FixLoop Trust Receipt Generator (W1).

Generates a plain-English, code-constructed summary directly from state fields.
Does NOT use model prose.
"""

from typing import Dict, Any, Optional
from pathlib import Path
import datetime
import re

def compute_diff_stats(diff_text: str, edit_root: str = "src/") -> Dict[str, Any]:
    """Parse unified diff into file list, added/removed line counts, and test preservation check."""
    if not diff_text or not diff_text.strip():
        return {
            "files": [],
            "added": 0,
            "removed": 0,
            "tests_and_config_untouched": True
        }

    files = set()
    added = 0
    removed = 0
    tests_touched = False

    for line in diff_text.splitlines():
        if line.startswith("+++ b/"):
            f = line[6:].strip()
            files.add(f)
            norm_f = f.replace("\\", "/")
            norm_root = edit_root.replace("\\", "/").rstrip("/") + "/"
            if not norm_f.startswith(norm_root):
                tests_touched = True
        elif line.startswith("+") and not line.startswith("+++"):
            added += 1
        elif line.startswith("-") and not line.startswith("---"):
            removed += 1

    return {
        "files": sorted(list(files)),
        "added": added,
        "removed": removed,
        "tests_and_config_untouched": not tests_touched
    }

def generate_receipt(state: Dict[str, Any], verdict_override: Optional[str] = None, diff_text: str = "") -> str:
    """Construct plain markdown trust receipt from state dictionary."""
    issue = state.get("issue", {})
    issue_title = issue.get("title", f"Issue {state.get('issue_id')}")
    test_node = state.get("test_node", "unknown")
    baseline = state.get("baseline", {})
    baseline_exit = baseline.get("exit_code", 1)

    status = state.get("status", "running")
    if verdict_override:
        verdict = verdict_override
    elif status in {"passed", "pr_opened"}:
        verdict = "FIXED, gate ok"
    elif status == "proposed_ungated":
        verdict = "PROPOSED UNGATED (experimental arm)"
    else:
        verdict = f"NOT FIXED: {state.get('hint') or 'stopped'}"

    # Oracle / fresh verification result
    oracle = state.get("oracle", {})
    oracle_resolved = oracle.get("resolved", False)
    if oracle_resolved:
        check_now = f"PASSED ({test_node} exited 0, regression test file exited 0)"
    elif status in {"passed", "pr_opened"} or verdict == "FIXED, gate ok":
        check_now = f"PASSED ({test_node} exited 0)"
    else:
        check_now = f"FAILED / UNVERIFIED ({test_node} did not pass gate)"

    # Compute diff stats
    stats = compute_diff_stats(diff_text, edit_root=state.get("edit_root", "src/"))
    files_str = ", ".join(stats["files"]) if stats["files"] else "None"
    untouched_str = "yes" if stats["tests_and_config_untouched"] else "no (WARNING: tests modified)"

    # Trace information
    trace_id = state.get("trace_id")
    last_span = state.get("last_span_id", "none")
    if trace_id:
        trace_str = f"https://app.neatlogs.com/projects/{state.get('project_id', '')}/traces/{trace_id}"
    else:
        trace_str = f"Local span ID: `{last_span}`"

    attempts = state.get("attempt", 1)
    tokens = state.get("tokens", 0)
    cost = state.get("cost_usd", 0.0)
    cost_str = f"${cost:.5f} USD" if cost > 0 else "UNKNOWN"

    lines = [
        "# FixLoop Trust Receipt",
        "",
        f"**Issue Title:** {issue_title}",
        f"**Verdict:** `{verdict}`",
        "",
        "## Verification Checks",
        f"- **Check That Failed Before (Baseline):** `{test_node}` (Exit Code {baseline_exit})",
        f"- **Check Now:** {check_now}",
        "",
        "## Scope of Changes",
        f"- **Files Changed:** `{files_str}`",
        f"- **Lines Modified:** `+{stats['added']} / -{stats['removed']}`",
        f"- **Tests and Config Unchanged:** **{untouched_str}**",
        "",
        "## Accounting & Telemetry",
        f"- **Verifying Attempts Used:** {attempts} / {state.get('max_attempts', 2)}",
        f"- **Total Model Tokens:** {tokens:,}",
        f"- **Total Model Cost:** {cost_str}",
        f"- **Observability Trace:** {trace_str}",
        "",
        "---",
        "*Receipt automatically generated by FixLoop code. No model prose was used in this verdict.*"
    ]
    return "\n".join(lines) + "\n"
